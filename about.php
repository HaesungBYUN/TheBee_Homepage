                function updateTabStyles(activeBtn, inactiveBtn) {
                    activeBtn.classList.add('border-b-2', 'border-solid', 'border-white');
                    inactiveBtn.classList.remove('border-b-2', 'border-solid', 'border-white');

                    const activeText = activeBtn.querySelector('.text-\[18px\]') || activeBtn.querySelector('div > div > div');
                    const inactiveText = inactiveBtn.querySelector('.text-\[18px\]') || inactiveBtn.querySelector('div > div > div');

                    if (activeText) {
                        activeText.classList.remove('font-normal', 'opacity-70');
                        activeText.classList.add('font-semibold');
                    }
                    if (inactiveText) {
                        inactiveText.classList.remove('font-semibold');
                        inactiveText.classList.add('font-normal', 'opacity-70');
                    }
                }

                tabIntroBtn.addEventListener('click', function (e) {
                    e.preventDefault();
                    tabIntro.style.display = 'block';
                    tabWork.style.display = 'none';
                    updateTabStyles(tabIntroBtn, tabWorkBtn);
                });

                tabWorkBtn.addEventListener('click', function (e) {
                    e.preventDefault();
                    tabIntro.style.display = 'none';
                    tabWork.style.display = 'block';
                    updateTabStyles(tabWorkBtn, tabIntroBtn);
                });

                // Init state
                updateTabStyles(tabIntroBtn, tabWorkBtn);
                tabIntro.style.display = 'block';
                tabWork.style.display = 'none';
            } else {
                console.error("Tab elements not found!");
            }
